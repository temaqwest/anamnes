def suggest_areas(title: str, personal_slugs: Mapping[str, str]) -> list[AreaSuggestion]:
    words = re.sub(r"[\W_]+", " ", normalize("NFKC", title))
    matches: dict[str, AreaSuggestion] = {}
    strong_spans: list[tuple[int, int]] = []
    for preset, pattern in STRONG_RULES.items():
        if slug := personal_slugs.get(preset):
            for match in pattern.finditer(words):
                strong_spans.append(match.span())
                matches.setdefault(preset, {"slug": slug, "matched_text": match.group(), "auto_select": True})

    strong = set(matches)
    for pattern, presets in AMBIGUOUS_RULES:
        if strong.intersection(presets):
            continue
        # A detailed phrase such as "цитология щитовидной железы" already explains this occurrence.
        match = next(
            (match for match in pattern.finditer(words)
             if not any(start <= match.start() and match.end() <= end for start, end in strong_spans)),
            None,
        )
        if match is None:
            continue
        for preset in presets:
            if (slug := personal_slugs.get(preset)) and preset not in matches:
                matches[preset] = {"slug": slug, "matched_text": match.group(), "auto_select": False}
    return list(matches.values())
